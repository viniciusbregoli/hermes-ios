#!/bin/sh
# Rebuilds Sources/HermesUI/Resources/screen.js: noVNC (MPL-2.0) plus scripts/screen/screen.js in one ES module.
# noVNC 1.7 uses top-level await, so the bundle stays an ES module (the app inlines it in a module script).
set -eu
NOVNC=1.7.0
here=$(cd "$(dirname "$0")" && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
cd "$work"
npm init -y >/dev/null
npm install --silent --no-audit --no-fund "@novnc/novnc@$NOVNC" esbuild@0.25.12
cp "$here/screen.js" screen.mjs
{
  echo "// Generated by scripts/screen/build.sh from noVNC $NOVNC (MPL-2.0, https://github.com/novnc/noVNC). Do not edit."
  npx esbuild screen.mjs --bundle --format=esm --minify --target=safari17 --legal-comments=none
} > "$here/../../Sources/HermesUI/Resources/screen.js"
